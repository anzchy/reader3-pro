// 013 WI-10: the pure half of the theme plugin (A10.11, spec §3.3, decision D6).
//
// Everything here is a function of its arguments: no node:*, no Vite. The Vite plugin
// (theme-plugin.ts) does the I/O -- scan the source tree, serve the virtual stylesheet --
// and calls into this file; Vitest calls the same functions directly, and the packaging
// test prints emitDarkCss through `node --experimental-strip-types`. That last use is
// why this module imports nothing: a type-stripped module cannot follow an alias.
//
// The one rule this file exists for: the dark chrome declarations are rendered ONCE
// and the same string is placed under both selectors -- the OS-dark media query (for
// "system") and the explicit `data-theme="dark"`. Two hand-maintained copies drift;
// one rendered string cannot.

export const DARK_MEDIA = "@media (prefers-color-scheme: dark)";
export const DARK_SYSTEM_SELECTOR = ':root:not([data-theme="light"])';
export const DARK_EXPLICIT_SELECTOR = ':root[data-theme="dark"]';

/** The reading papers get a rule each; `auto` deliberately has none (it inherits the chrome). */
const READING_SELECTOR = (paper: string): string => `html[data-reading-theme="${paper}"] .reader-shell`;

type Declarations = Readonly<Record<string, string>>;

export interface Source {
  path: string;
  text: string;
}

const UNSAFE_VALUE = /[;{}]/;

/** `  --a: 1;\n  --b: 2;\n`, in insertion order. Refuses a value that could end its declaration. */
export function renderDeclarations(decls: Declarations, indent = "  "): string {
  let out = "\n";
  for (const [name, value] of Object.entries(decls)) {
    if (!name.startsWith("--")) throw new Error(`theme token ${JSON.stringify(name)} is not a custom property`);
    if (UNSAFE_VALUE.test(value) || value.trim() === "") {
      throw new Error(`theme token ${name} has an unsafe or empty value ${JSON.stringify(value)}`);
    }
    out += `${indent}${name}: ${value};\n`;
  }
  return out;
}

/** The two dark rules, with one rendered body placed under both selectors. */
export function emitDarkCss(decls: Declarations): string {
  const body = renderDeclarations(decls, "    ");
  return (
    `${DARK_MEDIA} {\n  ${DARK_SYSTEM_SELECTOR} {${body}  }\n}\n` +
    `${DARK_EXPLICIT_SELECTOR} {${body}  }\n`
  );
}

/** light chrome on :root, the dark pair, then one rule per absolute paper (none for auto). */
export function emitThemeCss(
  chrome: Readonly<{ light: Declarations; dark: Declarations }>,
  reading: Readonly<Record<string, Declarations | null>>,
): string {
  let css = `/* generated by frontend/theme-plugin.ts from frontend/src/shared/theme-tokens.ts -- do not edit */\n`;
  css += `:root {${renderDeclarations(chrome.light)}}\n`;
  css += emitDarkCss(chrome.dark);
  for (const [paper, decls] of Object.entries(reading)) {
    if (decls === null) continue;
    css += `${READING_SELECTOR(paper)} {${renderDeclarations(decls)}}\n`;
  }
  return css;
}

// A definition is a declaration (`const|let|var CHROME_THEMES ... =`), not a use:
// imports, property reads and `===` comparisons do not match.
const DEFINITION_RE = /\b(?:const|let|var)\s+CHROME_THEMES\b\s*(?::[^=;]*)?=(?!=)/g;

function stripComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:"'])\/\/.*$/gm, "$1");
}

export function countDefinitions(sources: readonly Source[]): number {
  let n = 0;
  for (const { text } of sources) n += stripComments(text).match(DEFINITION_RE)?.length ?? 0;
  return n;
}

export function assertSingleAuthor(sources: readonly Source[]): void {
  const n = countDefinitions(sources);
  if (n !== 1) {
    const where = sources
      .filter(({ text }) => (stripComments(text).match(DEFINITION_RE)?.length ?? 0) > 0)
      .map(({ path }) => path);
    throw new Error(
      `CHROME_THEMES defined ${n} times (expected exactly 1, in frontend/src/shared/theme-tokens.ts)` +
        (where.length ? `: ${where.join(", ")}` : ""),
    );
  }
}

/** Handwritten stylesheets must not carry a dark chrome block: the plugin is its only author. */
const HANDWRITTEN_DARK_RE = /prefers-color-scheme\s*:\s*dark|\[\s*data-theme\s*=\s*["']?dark\b/;

export function assertNoHandwrittenDark(id: string, css: string): void {
  if (HANDWRITTEN_DARK_RE.test(css.replace(/\/\*[\s\S]*?\*\//g, ""))) {
    throw new Error(
      `${id}: handwritten dark chrome rule; dark declarations come only from CHROME_THEMES.dark via the theme plugin`,
    );
  }
}

"""Regenerate MATRIX.md (deterministic: no timestamps, pids, tmp paths or random ids).

    uv run python docs/plans/20260816-tech-stack-migration/tasks/evidence/q2-commit-prototype/gen_matrix.py
"""
from __future__ import annotations

import ast
import os
import sys
from collections import Counter
from typing import Iterable, List

EV = os.path.dirname(os.path.abspath(__file__))
if EV not in sys.path:
    sys.path.insert(0, EV)

from proto import harness as h  # noqa: E402

MATRIX = os.path.join(EV, "MATRIX.md")
STATES = ("missing", "old-valid", "new-valid", "corrupt")
LOC_FILES = {
    "A": ["proto/mech_a_journal.py"],
    "B": ["proto/mech_b_generation.py", "proto/generation_core.py"],
    "shared": ["proto/common.py"],
    "WI-7 fake index (reuses B core)": ["proto/fake_index.py"],
}
RECOVERY_FUNCS = {
    "proto/mech_a_journal.py": ("recover_a", "_rollback"),
    "proto/mech_b_generation.py": ("recover_b",),
    "proto/generation_core.py": ("recover_generations", "_gc", "read_generation"),
}


def code_lines(rel: str) -> int:
    """Non-blank, non-comment, non-docstring lines."""
    src = open(os.path.join(EV, rel), encoding="utf-8").read()
    doc = set()
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.ClassDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) \
                    and isinstance(first.value.value, str):
                doc.update(range(first.lineno, (first.end_lineno or first.lineno) + 1))
    return sum(1 for i, line in enumerate(src.splitlines(), 1)
               if line.strip() and not line.strip().startswith("#") and i not in doc)


def recovery_branches(rel: str) -> int:
    names = RECOVERY_FUNCS.get(rel, ())
    tree = ast.parse(open(os.path.join(EV, rel), encoding="utf-8").read())
    total = 0
    for fn in ast.walk(tree):
        if isinstance(fn, ast.FunctionDef) and fn.name in names:
            total += sum(isinstance(n, (ast.If, ast.IfExp)) for n in ast.walk(fn))
    return total


def table(header: List[str], rows: Iterable[Iterable[object]]) -> List[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return out


def render(res: h.Results) -> str:
    cells = sorted(res.cells, key=h.Cell.key)
    L = ["# Q2 commit prototype -- crash matrix", "",
         "Generated by `gen_matrix.py`; do not edit by hand. "
         "`test_q2_matrix_is_current` fails when this file is stale.", "",
         "Allowed final state: crash before the commit point -> `missing` (S0, S0u) or `old-valid` "
         "(S1-S3); at/after it -> `new-valid`. Never `corrupt`; residue must be 0; user files "
         "(`notes.json`, `ai_meta.json`) byte+inode+mtime_ns identical. Commit point: A `a10`, B `b8`, "
         "index `i8`. Every `exdev-simulated` row is a SIMULATED EXDEV (monkeypatched rename), not a "
         "second volume.", "", "## Scenarios", ""]
    L += table(["scenario", "meaning"], sorted(h.SCENARIO_DOC.items()))
    L += ["| I-old / I-empty | fake WI-7 index: republish over an old generation / first build |", ""]

    L += ["## Summary (final state after recovery)", ""]
    groups = sorted({(x.mech, x.mode) for x in cells})
    rows = []
    for mech, mode in groups:
        g = [x for x in cells if (x.mech, x.mode) == (mech, mode)]
        st = Counter(x.state for x in g)
        other = sum(v for k, v in st.items() if k not in STATES)
        rows.append([mech, mode, len(g)] + [st.get(s, 0) for s in STATES] + [
            other, sum(x.residue > 0 for x in g), sum(x.user == "NO" for x in g),
            sum(x.verdict != "PASS" for x in g)])
    L += table(["mechanism", "mode", "cells", *STATES, "other", "residue>0", "user NO", "FAIL"], rows)
    L += ["", f"Total cells: {len(cells)}; FAIL: {sum(x.verdict != 'PASS' for x in cells)}. "
          "`other` for the index rows is the fingerprint the query side resolves (`fp-old`/`fp-new`).", ""]

    L += ["## Liveview summary (unlocked concurrent reader, no crash; informational)", ""]
    rows = []
    for key in sorted({(r.mech, r.scenario) for r in res.live}):
        lr = [r for r in res.live if (r.mech, r.scenario) == key]
        st = Counter(r.state for r in lr)
        odd = [f"{r.step}:{r.when}" for r in lr if r.state not in ("missing", "old-valid", "new-valid")]
        rows.append([*key, len(lr), *(st.get(s, 0) for s in STATES), st.get("pkl-only-new", 0),
                     odd[0] if odd else "-", odd[-1] if odd else "-"])
    L += table(["mechanism", "scenario", "hook points", *STATES, "pkl-only-new",
                "first transient", "last transient"], rows)
    L += ["", "`pkl-only-new`: no manifest yet, but the new `book.pkl` is live, so a reader on the "
          "ADR-0009 `missing -> book.pkl` path already sees v2 before the commit point.", ""]

    L += ["## Disk usage of the book dir (bytes, file sizes only; dim 10)", ""]
    rows = [[m, s, d["before"], d["peak"], d["after"], f"{d['peak'] / max(d['after'], 1):.2f}"]
            for (m, s), d in sorted(res.disk.items())]
    L += table(["mechanism", "scenario", "before", "peak during publish", "after (B: after GC)",
                "peak / after"], rows)
    L += [""]

    L += ["## Code size (dim 8)", ""]
    rows = []
    for label, files in LOC_FILES.items():
        for rel in files:
            rows.append([label, rel, code_lines(rel), recovery_branches(rel)])
    L += table(["mechanism", "file", "code lines (no blank/comment/docstring)",
                "if-branches in recovery fns"], rows)
    a = sum(code_lines(f) for f in LOC_FILES["A"])
    b = sum(code_lines(f) for f in LOC_FILES["B"])
    L += ["", f"A total: {a} lines. B total (incl. generation_core): {b} lines.", ""]

    L += ["## Full crash matrix", ""]
    L += table(["mechanism", "scenario", "step", "before/after", "mode", "final state", "residue",
                "user_intact", "PASS/FAIL"],
               ([x.mech, x.scenario, x.step, x.when, x.mode, x.state, x.residue, x.user, x.verdict]
                for x in cells))
    L += ["", "## Liveview detail", ""]
    L += table(["mechanism", "scenario", "step", "before/after", "live state"],
               ([r.mech, r.scenario, r.step, r.when, r.state]
                for r in sorted(res.live, key=lambda r: (r.mech, r.scenario, r.order))))
    return "\n".join(L) + "\n"


def main() -> int:
    text = render(h.compute_all())
    with open(MATRIX, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
